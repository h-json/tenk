package com.hjson.tenk.domain.user;

/**
 * 탈퇴 사유 (선택 입력). 이탈 원인을 분류하기 위한 코드이며 서비스 기능에는 쓰이지 않는다.
 *
 * <p>항목을 바꾸면 Flutter 탈퇴 화면의 라벨 목록도 같은 코드로 동시에 갱신할 것
 * (표시 문구는 클라이언트가 들고, 여기엔 안정적인 코드만 둔다 — 지출 카테고리와 같은 방식).
 * 이미 쌓인 값은 그대로 남으므로 <b>기존 상수를 지우거나 이름을 바꾸지 말 것</b>.
 */
public enum WithdrawalReason {

    /** 사용하기 불편함 — 입력·조작 등 사용성 문제. */
    INCONVENIENT,

    /** 원하는 기능이 없음. */
    MISSING_FEATURE,

    /** 흥미가 떨어짐 — 동기 저하. */
    LOST_INTEREST,

    /** 목표를 이룸 — 부정적 이탈이 아니라 '졸업' 이라 지표에서 따로 봐야 한다. */
    GOAL_ACHIEVED,

    /** 다른 앱을 사용 중. */
    USING_OTHER_APP,

    /** 오류·불안정. */
    BUGS,

    /** 그 밖의 사유 — 자유 서술이 함께 올 수 있다. */
    ETC
}
